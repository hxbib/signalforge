"""Generate eval/RESULTS.md from eval/results/summary.json (+ the raw files it names) and print the per-arm table.

  .venv/bin/python eval/report.py            # rebuilds summary.json from eval/results/*.json first
Every number in RESULTS.md is read from those files; nothing is typed by hand.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import summarize  # noqa: E402

LABEL = {"baseline": "Baseline: 1× Gemini 4 Carbon call",
         "full": "System: Neon extract + Carbon verdict + quote check (app.models.pair)"}


def fmt_ms(lat):
    return f'{lat["median_ms"]/1000:.1f} s / {lat["p90_ms"]/1000:.1f} s' if lat else "–"


def arm_table(v):
    a = v["arms"]
    rows = ["| Arm | Correct | Wrong | Abstained | Errors | False accepts (of actual negatives) | Answered | Median / p90 latency |",
            "|---|---|---|---|---|---|---|---|"]
    for k in ("baseline", "full"):
        x = a[k]
        rows.append(f'| {LABEL[k]} | {x["correct"]}/{x["n"]} | {x["wrong"]} | {x["abstained"]} | {x["errors"]} | '
                    f'{x["false_accepts"]}/{x["actual_negatives"]} | {x["answered"]}/{x["n"]} | {fmt_ms(x["latency"])} |')
    return "\n".join(rows)


def stratum_table(v):
    rows = ["| Stratum (category/gold) | n | Baseline correct | System correct | System abstained | Baseline false accepts | System false accepts |",
            "|---|---|---|---|---|---|---|"]
    for s in v["by_stratum"]:
        b, f = s["baseline"], s["full"]
        rows.append(f'| {s["stratum"]} | {b["n"]} | {b["correct"]} | {f["correct"]} | {f["abstained"]} | {b["false_accepts"]} | {f["false_accepts"]} |')
    return "\n".join(rows)


def render(summary):
    out = ["# SignalForge evaluation results", "",
           "_Generated by `eval/report.py` from " + ", ".join(f"`eval/results/{n}`" for n in summary["generated_from"]) +
           ". Do not edit by hand._", ""]
    fr = summary.get("freeze")
    out += ["## Experiment A · does a listing describe the exact same product?", "",
            "Independent inputs we did not write or label: 40 listing pairs drawn blind from the **WDC Product Data Corpus v2** "
            "non-normalized gold standard (Peeters, Primpeli, Bizer; https://webdatacommons.org/largescaleproductcorpus/v2/), "
            "computers + cameras, 10 matching and 10 non-matching pairs per category. Models see only title, description, brand "
            "and spec text; ids, clusters and labels never enter a model input. The system arm is the same two-model listing "
            "check the live app uses to decide whether a merchant listing is the photographed item (identity tier "
            "`model_number`, `app.models.pair`). Abstentions and errors count as incorrect and stay in the denominator.", ""]
    if fr:
        out += [f'Frozen before either arm ran: {fr["frozen_at_iso"]}, seed = code SHA `{fr["seed"][:12]}`, '
                f'inputs sha256 `{fr["inputs_sha256"][:12]}…`, gold sha256 `{fr["gold_sha256"][:12]}…`, '
                f'corpus sha256 computers `{fr["corpus_sha256"]["computers"][:12]}…` cameras `{fr["corpus_sha256"]["cameras"][:12]}…`.', ""]
    for v in summary["versions"]:
        out += [f'### Run {v["version"]} · code `{v["code_sha"][:12]}` · models {", ".join(v["model_ids"]) or "–"}', "",
                arm_table(v), "",
                f'Paired outcomes on the same {v["n"]} packets: both correct {v["paired"]["both"]}, only system {v["paired"]["full_only"]}, '
                f'only baseline {v["paired"]["baseline_only"]}, neither {v["paired"]["neither"]}.', "",
                stratum_table(v), ""]
    eb = summary.get("experiment_b")
    out += ["## Experiment B · five fresh photo-to-offer shopping cases", ""]
    if eb:
        out += [f'Status: **{eb["status"]}**. {eb["statement"]}', ""] + [f"- {m}" for m in eb.get("missing", [])] + [""]
    else:
        out += ["No record.", ""]
    out += ["## Failure analysis", "", "See `eval/CHANGELOG.md` (system-arm failures read case by case).", "",
            "This is a listing-identity benchmark on public data; it is not a measure of end-to-end shopping accuracy, "
            "live stock or camera input. Published labels may be familiar to a pretrained model.", ""]
    return "\n".join(out)


def main():
    summarize.main()
    summary = json.loads((summarize.RESULTS / "summary.json").read_text())
    (HERE / "RESULTS.md").write_text(render(summary))
    for v in summary["versions"]:
        print(f'Experiment A run {v["version"]} (code {v["code_sha"][:12]}, n={v["n"]})')
        print(arm_table(v))
        print("paired:", v["paired"])
    print("wrote", HERE / "RESULTS.md")


if __name__ == "__main__":
    main()
